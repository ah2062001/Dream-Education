from django.contrib.auth.models import User
from django.core.validators import MinValueValidator
from django.db import models


class TeacherProfile(models.Model):
    user = models.OneToOneField(User, on_delete=models.CASCADE, related_name='teacher_profile')
    display_name = models.CharField(max_length=120)
    subject_specialty = models.CharField(max_length=120, blank=True)
    phone = models.CharField(max_length=30, blank=True)
    bio = models.TextField(blank=True)

    class Meta:
        ordering = ['display_name']

    def __str__(self):
        return self.display_name


class TeachingSchedule(models.Model):
    WEEKDAY_CHOICES = [
        ('Monday', 'Monday'),
        ('Tuesday', 'Tuesday'),
        ('Wednesday', 'Wednesday'),
        ('Thursday', 'Thursday'),
        ('Friday', 'Friday'),
        ('Saturday', 'Saturday'),
        ('Sunday', 'Sunday'),
    ]

    teacher = models.ForeignKey(TeacherProfile, on_delete=models.CASCADE, related_name='teaching_schedules')
    title = models.CharField(max_length=150)
    subject = models.CharField(max_length=120)
    student_name = models.CharField(max_length=120)
    student_details = models.CharField(max_length=220, blank=True)
    weekdays = models.CharField(max_length=120, help_text='Comma-separated weekdays generated by admin form')
    start_date = models.DateField()
    end_date = models.DateField()
    start_time = models.TimeField()
    end_time = models.TimeField()
    location = models.CharField(max_length=100, blank=True)
    notes = models.CharField(max_length=220, blank=True)

    class Meta:
        ordering = ['teacher__display_name', 'start_date', 'start_time', 'title']

    def __str__(self):
        return f"{self.teacher} - {self.title}"

    @property
    def weekday_list(self):
        return [item.strip() for item in self.weekdays.split(',') if item.strip()]

    @property
    def classes_per_week(self):
        return len(self.weekday_list)


class Student(models.Model):
    PROGRAM_CHOICES = [
        ('math', 'Math'),
        ('science', 'Science'),
        ('english', 'English'),
        ('ielts', 'IELTS'),
    ]

    teacher = models.ForeignKey(TeacherProfile, on_delete=models.CASCADE, related_name='students')
    student_type = models.CharField(max_length=20, choices=PROGRAM_CHOICES, default='english')
    full_name = models.CharField(max_length=120)
    preferred_name = models.CharField(max_length=60, blank=True)
    school_name = models.CharField(max_length=120, blank=True)
    year_group = models.CharField(max_length=50, blank=True)
    guardian_name = models.CharField(max_length=120, blank=True)
    guardian_contact = models.CharField(max_length=60, blank=True)
    notes = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['full_name']

    def __str__(self):
        return self.full_name


class ClassUpdate(models.Model):
    UPDATE_TYPES = [
        ('daily', 'Daily'),
        ('weekly', 'Weekly'),
        ('monthly', 'Monthly'),
    ]

    student = models.ForeignKey(Student, on_delete=models.CASCADE, related_name='updates')
    update_type = models.CharField(max_length=10, choices=UPDATE_TYPES)
    lesson_date = models.DateField()
    title = models.CharField(max_length=150)
    work_done = models.TextField()
    homework = models.TextField(blank=True)
    class_marks = models.PositiveIntegerField(null=True, blank=True, validators=[MinValueValidator(0)])
    max_marks = models.PositiveIntegerField(null=True, blank=True, validators=[MinValueValidator(1)])
    teacher_comment = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    @property
    def percentage(self):
        if self.class_marks is not None and self.max_marks:
            return round((self.class_marks / self.max_marks) * 100, 2)
        return None

    class Meta:
        ordering = ['-lesson_date', '-created_at']

    def __str__(self):
        return f"{self.student} - {self.get_update_type_display()} - {self.lesson_date}"


class TestScore(models.Model):
    PERIOD_CHOICES = [
        ('weekly', 'Weekly'),
        ('monthly', 'Monthly'),
    ]

    student = models.ForeignKey(Student, on_delete=models.CASCADE, related_name='test_scores')
    period_type = models.CharField(max_length=10, choices=PERIOD_CHOICES)
    assessment_name = models.CharField(max_length=150)
    score = models.PositiveIntegerField(validators=[MinValueValidator(0)])
    total_marks = models.PositiveIntegerField(validators=[MinValueValidator(1)])
    assessment_date = models.DateField()
    remarks = models.CharField(max_length=200, blank=True)

    class Meta:
        ordering = ['-assessment_date', '-id']

    @property
    def percentage(self):
        if self.total_marks:
            return round((self.score / self.total_marks) * 100, 2)
        return 0

    def __str__(self):
        return f"{self.student} - {self.assessment_name}"
